import { contextBridge, ipcRenderer, webUtils } from 'electron';
import type { DesktopAPI, DesktopEvent } from '../src/platform';
const invoke = (name: string, ...args: unknown[]) => ipcRenderer.invoke('deploy:' + name, ...args);
const api: DesktopAPI = {
  updateState: () => invoke('update-state'),
  checkUpdate: () => invoke('check-update'),
  downloadUpdate: () => invoke('download-update'),
  cancelUpdate: () => invoke('cancel-update'),
  installUpdate: () => invoke('install-update'),
  load: () => invoke('load'),
  save: (db) => invoke('save', db),
  confirmRecovery: () => invoke('confirm-recovery'),
  prepare: (value) => invoke('prepare', value),
  start: (token, values, approval) => invoke('start', token, values, approval),
  cancel: (id) => invoke('cancel', id),
  recover: (id, values) => invoke('recover', id, values),
  choose: (kind) => invoke('choose', kind),
  inspectJar: (file) => invoke('inspect-jar', file),
  localDifferences: () => invoke('local-differences'),
  serviceInfo: (id, file) => invoke('service-info', id, file),
  precheck: (request) => invoke('precheck', request),
  toolInfo: (id) => invoke('tool-info', id),
  sshAliases: (file) => invoke('ssh-aliases', file),
  testDraft: (server, credential) => invoke('test-draft', server, credential),
  diagnose: (target, kind, credential) => invoke('diagnose', target, kind, credential),
  serverHealth: (id, credential) => invoke('server-health', id, credential),
  acceptDrop: (file) => invoke('approve-dropped-jar', webUtils.getPathForFile(file)),
  detectJdks: () => invoke('detect-jdks'),
  checkTool: (kind, value) => invoke('check-tool', kind, value),
  resolveAlias: (id) => invoke('resolve-alias', id),
  inspectWorkbench: (id, credential) => invoke('inspect-workbench', id, credential),
  resolveWorkbench: (token, confirmation) => invoke('resolve-workbench', token, confirmation),
  cancelWorkbenchReview: (token) => invoke('cancel-workbench-review', token),
  inspectLock: (id, value) => invoke('inspect-lock', id, value),
  takeoverLock: (token, word) => invoke('takeover-lock', token, word),
  testConnection: (id, value) => invoke('test-connection', id, value),
  trust: (id, accepted, confirmation) => invoke('trust', id, accepted, confirmation),
  saveCredential: (id, value) => invoke('save-credential', id, value),
  deleteCredential: (id) => invoke('delete-credential', id),
  exportConfig: () => invoke('export-config'),
  importConfig: () => invoke('import-config'),
  readLogs: (id, target, before) => invoke('read-logs', id, target, before),
  exportLogs: (id, target) => invoke('export-logs', id, target),
  followLogs: (id, value) => invoke('follow-logs', id, value),
  stopLogs: (id) => invoke('stop-logs', id),
  readLogSession: (id) => invoke('read-log-session', id),
  searchHistory: (query) => invoke('search-history', query),
  cancelSearch: () => invoke('cancel-search'),
  exportReport: (id) => invoke('export-report', id),
  previewBackups: (id, credential) => invoke('preview-backups', id, credential),
  applyBackups: (token, ids, confirmation) => invoke('apply-backups', token, ids, confirmation),
  cancelBackupPlan: (token) => invoke('cancel-backup-plan', token),
  backupAudits: (id) => invoke('backup-audits', id),
  reconcileBackup: (id, credential) => invoke('reconcile-backup', id, credential),
  listTasks: () => invoke('list-tasks'),
  readTask: (id) => invoke('read-task', id),
  openDataDir: () => invoke('open-data-dir'),
  dataUsage: () => invoke('data-usage'),
  previewCleanup: (kind, policy) => invoke('preview-cleanup', kind, policy),
  applyCleanup: (token, confirmed) => invoke('apply-cleanup', token, confirmed),
  snapshotAvailability: (id) => invoke('snapshot-availability', id),
  directoryInfo: () => invoke('data-directory'),
  inspectDirectory: (path) => invoke('inspect-directory', path),
  migrateDirectory: (path) => invoke('migrate-directory', path),
  cancelMigration: () => invoke('cancel-migration'),
  migrationState: () => invoke('migration-state'),
  restart: () => invoke('restart'),
  keepOldData: () => invoke('keep-old-data'),
  removeOldData: (path) => invoke('remove-old-data', path),
  help: () => invoke('help'),
  about: () => invoke('about'),
  onEvent: (callback) => {
    const listener = (_event: Electron.IpcRendererEvent, value: DesktopEvent) => callback(value);
    ipcRenderer.on('deploy:event', listener);
    return () => ipcRenderer.removeListener('deploy:event', listener);
  },
};
contextBridge.exposeInMainWorld('deployCenter', Object.freeze(api));
