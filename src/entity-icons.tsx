/** 图标名 → lucide 组件，由 ENTITY_ICON_LIST 派生，避免清单与映射各维护一遍。 */
export const ENTITY_ICONS: Record<string, LucideIcon> = Object.fromEntries(
  ENTITY_ICON_LIST.map(({ name, Icon }) => [name, Icon]),
);

/** 各实体缺省图标（未设置时回落）。 */
export const DEFAULT_ENTITY_ICON: Record<EntityIconKind, string> = {
  service: 'Boxes',
  server: 'Server',
  target: 'Target',
};

